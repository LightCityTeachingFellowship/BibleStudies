import assert from 'node:assert/strict';
import { createVideoStore, resumeSeconds } from '../../script/video-personal-store.mjs';
const values=new Map(), storage={getItem:k=>values.get(k),setItem:(k,v)=>values.set(k,v)};
let now=1000;const store=createVideoStore({storage,now:()=>++now});
const a='abcdefghijk', b='ABCDEFGHIJK';
store.save(a,'Teaching',true);assert.ok(store.saved(a));
store.progress({videoId:a,seconds:120.5,duration:600,rate:1.25,mode:'video'});
assert.equal(resumeSeconds(store.history(a)),120.5);
store.progress({videoId:a,seconds:30,duration:600,rate:1,mode:'audio'});
assert.equal(resumeSeconds(store.history(a)),30,'a deliberate backward seek replaces the previous position');
store.progress({videoId:a,seconds:600,duration:600,rate:1,mode:'audio',completed:true});
assert.equal(resumeSeconds(store.history(a)),0,'finished video restarts from the beginning');
store.setIdentity('alice');assert.equal(store.saved(a),false,'guest data is not exposed in another scope');
store.save(a,'Private video',true);const [key,old]=store.pending()[0];store.save(a,'Private video',false);store.acknowledge(key,old);assert.equal(store.pending().length,1,'an old sync response cannot erase a newer edit');
store.hydrate('saved',[{videoId:a,title:'Old server copy',updatedAt:10}]);assert.equal(store.saved(a),false,'pending removal wins over hydration');
store.save(b,'Saved',true);store.progress({videoId:b,seconds:100,duration:1000,mode:'video',rate:1});store.clearHistory();
assert.equal(store.history(b),null);assert.ok(store.saved(b),'clear history preserves bookmarks');
assert.ok(store.pending().some(([,op])=>op.action==='clearHistory'));
store.hydrate('history',[{videoId:b,seconds:90,updatedAt:5}]);assert.equal(store.history(b),null);
store.setIdentity('bob');assert.equal(store.saved(b),false,'account switch cannot expose another account saved list');
store.setIdentity('alice');assert.ok(store.saved(b),'account cache remains scoped to its owner');
store.setIdentity(null);assert.ok(store.saved(a),'returning guest sees only guest bookmarks');
assert.equal(store.history(a).completed,true);
console.log('PASS: scoped guest/account bookmarks, exact and backward resume positions, completion, offline edits, stale sync acknowledgements, account isolation, and history clearing.');
