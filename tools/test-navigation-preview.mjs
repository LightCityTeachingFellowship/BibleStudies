import assert from 'node:assert/strict';
import {sectionFor, pageFor, shouldNavigate} from '../script/navigation-preview.mjs';
assert.equal(sectionFor(new URL('../Home/', import.meta.url).href), 'home');
assert.equal(sectionFor(new URL('../Videos/', import.meta.url).href), 'videos');
assert.equal(sectionFor(new URL('../Listen/', import.meta.url).href), 'audio');
assert.equal(sectionFor(new URL('../Teaching-Articles/', import.meta.url).href), 'articles');
assert.equal(sectionFor(new URL('../teaching-summary/', import.meta.url).href), 'summaries');
assert.equal(sectionFor(new URL('../Watch/?v=12345678901', import.meta.url).href), null);
assert.equal(sectionFor('https://example.invalid/Home/'), null);
assert.ok(pageFor(new URL('../some-article/', import.meta.url).href));
assert.ok(pageFor(new URL('../StudyResource/?id=example', import.meta.url).href));
assert.ok(pageFor(new URL('../Watch/?v=12345678901', import.meta.url).href));
assert.ok(pageFor(new URL('../members/', import.meta.url).href));
assert.equal(pageFor(new URL('../images/file.png', import.meta.url).href), null);
const link = { target: '', hasAttribute: () => false };
assert.equal(shouldNavigate({button:0}, link), true);
assert.equal(shouldNavigate({button:0,ctrlKey:true}, link), false);
assert.equal(shouldNavigate({button:1}, link), false);
assert.equal(shouldNavigate({button:0}, {...link,target:'_blank'}), false);
console.log('PASS: main sections, route exclusions and normal browser link gestures');
